using Shouldly;
using Watchpoint.Host.Nats;
using Watchpoint.Hosting.Supervision;
using Xunit;

namespace Watchpoint.Hosting.Tests;

/// <summary>Bundled NATS configuration, token and version check (spec HST §7.4).</summary>
[Trait("layer", "U")]
[Trait("spec", "HST")]
public sealed class BundledNatsTests : IDisposable
{
    private const long Gigabyte = 1024L * 1024 * 1024;

    private readonly string _data = Path.Combine(Path.GetTempPath(), "wp-nats-" + Guid.NewGuid().ToString("N"));

    private static CancellationToken Ct => TestContext.Current.CancellationToken;

    public void Dispose()
    {
        if (Directory.Exists(_data))
        {
            Directory.Delete(_data, recursive: true);
        }
    }

    [Fact]
    public void HST_U_023_NATS_config_generation()
    {
        var factory = Factory(free: 100 * Gigabyte, port: 4333);
        var token = factory.EnsureToken();
        var store = Path.Combine(_data, "nats", "store").Replace('\\', '/');

        var config = factory.BuildConfig(File.ReadAllText(factory.TokenPath));

        config.ShouldBe(
            "# Generated by Watchpoint at every start; changes are overwritten.\n" +
            "listen: 127.0.0.1:4333\n" +
            "server_name: \"01937b5e-8c00-7000-8000-000000000001\"\n" +
            "jetstream {\n" +
            $"  store_dir: \"{store}\"\n" +
            "  max_memory_store: 256MB\n" +
            "  max_file_store: 21474836480\n" +
            "}\n" +
            "authorization {\n" +
            $"  token: \"{token}\"\n" +
            "}\n" +
            "max_payload: 4MB\n");

        // 20 % of the free disk, but never less than 10 GB.
        Factory(free: 3 * Gigabyte).BuildConfig(token).ShouldContain("  max_file_store: 10737418240\n");

        // The process: the generated file, readiness on the loopback port, log lines at Information.
        var spec = factory.Create();
        File.ReadAllText(factory.ConfigPath).ShouldBe(config);
        spec.Name.ShouldBe("nats");
        spec.Executable.ShouldBe(Path.GetFullPath(factory.ExecutablePath));
        spec.Arguments.ShouldBe(["-c", factory.ConfigPath]);
        spec.Readiness.ShouldBe(new ReadinessProbe.Tcp("127.0.0.1", 4333, TimeSpan.FromSeconds(30)));
        spec.Arguments.ShouldNotContain(a => a.Contains(token, StringComparison.Ordinal));
        spec.Environment.ShouldBeEmpty();
        factory.Endpoint().ShouldBe(new NatsEndpoint("nats://127.0.0.1:4333", token));
        factory.Endpoint().ToString().ShouldNotContain(token);

        // External mode: the settings, no token file involved.
        var external = new NodeSettings { Nats = { Mode = NatsMode.External, Url = "nats://nats.example:4222", Token = "devtoken" } };
        new NatsProcessSpecFactory(external, Paths()).Endpoint().ShouldBe(new NatsEndpoint("nats://nats.example:4222", "devtoken"));
    }

    [Fact]
    public void HST_U_024_NATS_token_file_created_owner_only()
    {
        var factory = Factory();

        var token = factory.EnsureToken();

        File.Exists(factory.TokenPath).ShouldBeTrue();
        File.ReadAllText(factory.TokenPath).ShouldBe(token);
        token.Length.ShouldBe(43);
        Convert.FromBase64String(token.Replace('-', '+').Replace('_', '/') + "=").Length.ShouldBe(32);
        factory.EnsureToken().ShouldBe(token);
        factory.Create();
        if (!OperatingSystem.IsWindows())
        {
            const UnixFileMode OwnerOnly = UnixFileMode.UserRead | UnixFileMode.UserWrite;
            File.GetUnixFileMode(factory.TokenPath).ShouldBe(OwnerOnly);
            File.GetUnixFileMode(factory.ConfigPath).ShouldBe(OwnerOnly);
            File.GetUnixFileMode(factory.StorePath).ShouldBe(OwnerOnly | UnixFileMode.UserExecute);
        }

        // Random: another node gets another token; a damaged file is replaced, still owner-only.
        var other = new NatsProcessSpecFactory(new NodeSettings(), Paths(Path.Combine(_data, "other")));
        other.EnsureToken().ShouldNotBe(token);
        File.WriteAllText(factory.TokenPath, "short");
        var replaced = factory.EnsureToken();
        replaced.Length.ShouldBe(43);
        replaced.ShouldNotBe(token);
        if (!OperatingSystem.IsWindows())
        {
            File.GetUnixFileMode(factory.TokenPath).ShouldBe(UnixFileMode.UserRead | UnixFileMode.UserWrite);
        }
    }

    [Fact]
    public async Task HST_U_042_NATS_binary_location_and_version_check()
    {
        NatsProcessSpecFactory.ParseVersion("nats-server: v2.15.2\n").ShouldBe(new Version(2, 15, 2));
        NatsProcessSpecFactory.ParseVersion("no version here").ShouldBeNull();
        NatsProcessSpecFactory.EnsureSupported("nats-server: v2.12.0").ShouldBe(new Version(2, 12, 0));

        var old = Should.Throw<SupervisorException>(() => NatsProcessSpecFactory.EnsureSupported("nats-server: v2.11.9"));
        old.Error.Code.Value.ShouldBe("host.nats.version_unsupported");
        old.Error.Kind.ShouldBe(Watchpoint.Kernel.Results.ErrorKind.Unprocessable);
        Should.Throw<SupervisorException>(() => NatsProcessSpecFactory.EnsureSupported(string.Empty))
            .Error.Code.Value.ShouldBe("host.nats.version_unsupported");

        // <Paths:Binaries>/nats-server(.exe); a missing binary is reported before anything is started.
        var factory = Factory();
        factory.ExecutablePath.ShouldBe(Path.Combine(_data, "bin", OperatingSystem.IsWindows() ? "nats-server.exe" : "nats-server"));
        var missing = await Should.ThrowAsync<SupervisorException>(() => factory.ReadVersionAsync(TimeProvider.System, Ct));
        missing.Error.Code.Value.ShouldBe("host.process.executable_missing");
    }

    private NodePaths Paths(string? data = null)
    {
        data ??= _data;
        return new NodePaths(data, Path.Combine(data, "logs"), Path.Combine(data, "integrations"), Path.Combine(data, "bin"));
    }

    private NatsProcessSpecFactory Factory(long free = 100 * Gigabyte, int port = 4222)
    {
        var settings = new NodeSettings { Node = { Id = Guid.Parse("01937b5e-8c00-7000-8000-000000000001") }, Nats = { Port = port } };
        return new NatsProcessSpecFactory(settings, Paths(), _ => free);
    }
}
