using System.Globalization;
using System.Text;
using System.Text.Json;
using Watchpoint.Model.Documents;
using Watchpoint.Model.Documents.Library;

namespace Watchpoint.Wptypes;

/// <summary><c>wptypes doc</c>: a Markdown catalogue of capabilities and types, in a stable order.</summary>
internal static class MarkdownCatalogue
{
    public static string Generate(LibrarySet set)
    {
        var md = new StringBuilder();
        md.Append("# Type catalogue\n\n");
        md.Append("Generated by `wptypes doc`. Do not edit.\n\n");
        md.Append("## Capabilities\n");
        foreach (var capability in Catalogue.Capabilities(set))
        {
            var key = $"capabilities.{capability.Id}";
            md.Append(Inv($"\n### `{capability.Id}` {capability.Version} — {Catalogue.English(set, key + ".name") ?? capability.Id.Value}\n\n"));
            if (Catalogue.English(set, key + ".description") is { } description)
            {
                md.Append(description).Append("\n\n");
            }

            if (capability.Properties.Count > 0)
            {
                md.Append("| Property | Type | Values |\n|---|---|---|\n");
                foreach (var p in capability.Properties)
                {
                    md.Append(Inv($"| `{p.Id}` {Catalogue.English(set, $"{key}.properties.{p.Id}.name")} | {PropertyType(p)} | {Values(p)} |\n"));
                }

                md.Append('\n');
            }

            if (capability.Commands.Count > 0)
            {
                md.Append("| Command | Risk | Parameters |\n|---|---|---|\n");
                foreach (var c in capability.Commands)
                {
                    var risk = c.RiskByArgument is { Count: > 0 } ? $"{c.Risk} (by argument)" : c.Risk;
                    md.Append(Inv($"| `{c.Id}` {Catalogue.English(set, $"{key}.commands.{c.Id}.name")} | {risk} | {Parameters(c.Parameters.RawElement)} |\n"));
                }

                md.Append('\n');
            }

            if (capability.Events.Count > 0)
            {
                md.Append("| Event | Severity | Payload |\n|---|---|---|\n");
                foreach (var e in capability.Events)
                {
                    md.Append(Inv($"| `{e.Id}` {Catalogue.English(set, $"{key}.events.{e.Id}.name")} | {e.Severity} | {Parameters(e.Payload?.RawElement)} |\n"));
                }

                md.Append('\n');
            }
        }

        md.Append("## Device and server types\n\n");
        md.Append("| Type | Name | Role | Category | Licence | Capabilities | Primary property |\n|---|---|---|---|---|---|---|\n");
        foreach (var t in Catalogue.Types(set))
        {
            var capabilities = string.Join(", ", t.Capabilities.Select(c => c.Optional ? $"{c.Id} (optional)" : c.Id.Value));
            md.Append(Inv($"| `{t.Id}` {t.Version} | {Catalogue.English(set, $"types.{t.Id}.name")} | {Camel(t.Role.ToString())} | {Camel(t.Category.ToString())} | {Camel(t.LicenceClass.ToString())} | {capabilities} | `{t.Display.PrimaryProperty}` |\n"));
        }

        return md.ToString();
    }

    private static string PropertyType(PropertyDefinitionDoc p) => p.ValueType switch
    {
        "list" => $"list of {p.ItemType}",
        "decimal" or "integer" when p.Unit is not null => $"{p.ValueType} ({p.Unit})",
        _ => p.ValueType,
    };

    private static string Values(PropertyDefinitionDoc p)
    {
        if (p.EnumValues is { Count: > 0 } values)
        {
            return string.Join(", ", values.Select(v => $"`{v.Code}` {v.Severity}"));
        }

        if (p.BooleanSeverity is { } b)
        {
            return $"true {b.True}, false {b.False}";
        }

        return p.Range is { } r ? string.Create(CultureInfo.InvariantCulture, $"{r.Min} – {r.Max}") : string.Empty;
    }

    private static string Parameters(JsonElement? schema)
    {
        var required = Catalogue.Required(schema);
        return string.Join(", ", Catalogue.Fields(schema).Select(f =>
            $"`{f.Name}{(required.Contains(f.Name) ? string.Empty : "?")}`: {f.Definition.GetProperty("type").GetString()}"));
    }

    private static string Camel(string pascal) => char.ToLowerInvariant(pascal[0]) + pascal[1..];

    private static string Inv(FormattableString text) => text.ToString(CultureInfo.InvariantCulture);
}
