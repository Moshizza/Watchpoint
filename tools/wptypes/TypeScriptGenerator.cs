using System.Globalization;
using System.Text;
using System.Text.Json;
using Watchpoint.Model.Documents;
using Watchpoint.Model.Documents.Library;

namespace Watchpoint.Wptypes;

/// <summary><c>wptypes gen-ts</c>: TypeScript types of a library's capabilities and types (used by the UI packages).</summary>
internal static class TypeScriptGenerator
{
    public const string FileName = "watchpoint-types.ts";

    public static string Generate(LibrarySet set)
    {
        var capabilities = Catalogue.Capabilities(set).GroupBy(c => c.Id.Value).Select(g => g.Last()).ToList();
        var types = Catalogue.Types(set).GroupBy(t => t.Id.Value).Select(g => g.Last()).ToList();
        var ts = new StringBuilder();
        ts.Append("// Generated by wptypes gen-ts. Do not edit.\n\n");
        ts.Append("export type Severity = 'normal' | 'normalActive' | 'info' | 'warning' | 'alarm' | 'fault' | 'offline' | 'unknown';\n\n");
        ts.Append("export type CapabilityId = ").Append(Union(capabilities.Select(c => c.Id.Value))).Append(";\n\n");
        ts.Append("export type TypeId = ").Append(Union(types.Select(t => t.Id.Value))).Append(";\n");

        foreach (var c in capabilities)
        {
            var name = Pascal(c.Id.Value);
            ts.Append(CultureInfo.InvariantCulture, $"\n/** Capability `{c.Id}` {c.Version}. */\n");
            ts.Append(CultureInfo.InvariantCulture, $"export interface {name}Properties {{\n");
            foreach (var p in c.Properties)
            {
                ts.Append(CultureInfo.InvariantCulture, $"  readonly {p.Id}: {PropertyType(p)};\n");
            }

            ts.Append("}\n\n");
            ts.Append(CultureInfo.InvariantCulture, $"export interface {name}Commands {{\n");
            foreach (var command in c.Commands)
            {
                ts.Append(CultureInfo.InvariantCulture, $"  readonly {command.Id}: {ObjectType(command.Parameters.RawElement, "  ")};\n");
            }

            ts.Append("}\n\n");
            ts.Append(CultureInfo.InvariantCulture, $"export interface {name}Events {{\n");
            foreach (var e in c.Events)
            {
                ts.Append(CultureInfo.InvariantCulture, $"  readonly {e.Id}: {ObjectType(e.Payload?.RawElement, "  ")};\n");
            }

            ts.Append("}\n");
        }

        foreach (var kind in new[] { "Properties", "Commands", "Events" })
        {
            ts.Append(CultureInfo.InvariantCulture, $"\nexport interface Capability{kind} {{\n");
            foreach (var c in capabilities)
            {
                ts.Append(CultureInfo.InvariantCulture, $"  readonly {Key(c.Id.Value)}: {Pascal(c.Id.Value)}{kind};\n");
            }

            ts.Append("}\n");
        }

        ts.Append("\n/** Severity of each enum value. */\n");
        ts.Append("export const enumSeverities = {\n");
        foreach (var c in capabilities.Where(c => c.Properties.Any(p => p.EnumValues is { Count: > 0 })))
        {
            ts.Append(CultureInfo.InvariantCulture, $"  {Key(c.Id.Value)}: {{\n");
            foreach (var p in c.Properties.Where(p => p.EnumValues is { Count: > 0 }))
            {
                ts.Append(CultureInfo.InvariantCulture, $"    {p.Id}: {{ ").Append(string.Join(", ", p.EnumValues!.Select(v => $"{v.Code}: '{v.Severity}'"))).Append(" },\n");
            }

            ts.Append("  },\n");
        }

        ts.Append("} as const satisfies Partial<Record<CapabilityId, Record<string, Record<string, Severity>>>>;\n");

        ts.Append("\n/** Capabilities of each type (own uses; optional ones included). */\n");
        ts.Append("export const typeCapabilities = {\n");
        foreach (var t in types)
        {
            ts.Append(CultureInfo.InvariantCulture, $"  {Key(t.Id.Value)}: [").Append(string.Join(", ", t.Capabilities.Select(u => $"'{u.Id}'"))).Append("],\n");
        }

        ts.Append("} as const satisfies Record<TypeId, readonly string[]>;\n");
        return ts.ToString();
    }

    private static string PropertyType(PropertyDefinitionDoc p) => p.ValueType switch
    {
        "list" => $"ReadonlyArray<{ScalarValueType(p.ItemType ?? "string", p.EnumValues)}>",
        "object" => ObjectType(p.ObjectSchema?.RawElement, "  "),
        _ => ScalarValueType(p.ValueType, p.EnumValues),
    };

    private static string ScalarValueType(string valueType, IReadOnlyList<EnumValueDoc>? values) => valueType switch
    {
        "boolean" => "boolean",
        "integer" or "decimal" => "number",
        "enum" => values is { Count: > 0 } ? Union(values.Select(v => v.Code.Value)) : "string",
        "geoPoint" => "{ readonly lat: number; readonly lon: number }",
        _ => "string",
    };

    private static string ObjectType(JsonElement? schema, string indent)
    {
        var fields = Catalogue.Fields(schema);
        if (fields.Count == 0)
        {
            return "Record<string, never>";
        }

        var required = Catalogue.Required(schema);
        var sb = new StringBuilder("{\n");
        foreach (var (name, definition) in fields)
        {
            sb.Append(CultureInfo.InvariantCulture, $"{indent}  readonly {name}{(required.Contains(name) ? string.Empty : "?")}: {FieldType(definition, indent + "  ")};\n");
        }

        return sb.Append(indent).Append('}').ToString();
    }

    private static string FieldType(JsonElement field, string indent)
    {
        if (field.TryGetProperty("enum", out var values) && values.ValueKind == JsonValueKind.Array)
        {
            return string.Join(" | ", values.EnumerateArray().Select(v => v.ValueKind == JsonValueKind.String ? $"'{Escape(v.GetString()!)}'" : v.GetRawText()));
        }

        return field.GetProperty("type").GetString() switch
        {
            "integer" or "number" => "number",
            "boolean" => "boolean",
            "array" => $"ReadonlyArray<{FieldType(field.GetProperty("items"), indent)}>",
            "object" => ObjectType(field, indent),
            _ => "string",
        };
    }

    private static string Union(IEnumerable<string> values)
    {
        var list = values.Select(v => $"'{Escape(v)}'").ToList();
        return list.Count == 0 ? "never" : string.Join(" | ", list);
    }

    private static string Key(string id) => id.Contains('.', StringComparison.Ordinal) || id.Contains('-', StringComparison.Ordinal) ? $"'{id}'" : id;

    private static string Pascal(string id) =>
        string.Concat(id.Split('.', '-').Where(s => s.Length > 0).Select(s => char.ToUpperInvariant(s[0]) + s[1..]));

    private static string Escape(string text) => text.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("'", "\\'", StringComparison.Ordinal);
}
