using Watchpoint.Kernel.Ids;
using Watchpoint.Kernel.Values;
using Watchpoint.Model.Contracts;

namespace Watchpoint.Pipeline.Contracts;

/// <summary>What an observation reports (spec PIP §6).</summary>
public enum ObservationKind
{
    /// <summary>A property value.</summary>
    Property = 0,

    /// <summary>A device event.</summary>
    Event = 1,

    /// <summary>The health of a device or server.</summary>
    Health = 2,
}

/// <summary>Something a connection observed on a device or server (spec PIP §6).</summary>
public sealed record Observation
{
    /// <summary>Gets the observation id (UUID v7), generated by the sink; the deduplication key.</summary>
    public required Guid Id { get; init; }

    /// <summary>Gets what is reported.</summary>
    public required ObservationKind Kind { get; init; }

    /// <summary>Gets the device; exactly one of <see cref="Device"/> and <see cref="Server"/> is set.</summary>
    public DeviceId? Device { get; init; }

    /// <summary>Gets the server; exactly one of <see cref="Device"/> and <see cref="Server"/> is set.</summary>
    public ServerId? Server { get; init; }

    /// <summary>Gets the property (<see cref="ObservationKind.Property"/>).</summary>
    public PropertyPath? Property { get; init; }

    /// <summary>Gets the value (<see cref="ObservationKind.Property"/>).</summary>
    public WpValue Value { get; init; }

    /// <summary>Gets the unit the value was reported in, if it differs from the type's unit.</summary>
    public string? ReportedUnit { get; init; }

    /// <summary>Gets the quality of the value.</summary>
    public Quality Quality { get; init; } = Quality.Good;

    /// <summary>Gets the event (<see cref="ObservationKind.Event"/>).</summary>
    public EventPath? Event { get; init; }

    /// <summary>Gets the event fields (<see cref="ObservationKind.Event"/>).</summary>
    public IReadOnlyDictionary<string, WpValue>? Payload { get; init; }

    /// <summary>Gets the health (<see cref="ObservationKind.Health"/>).</summary>
    public HealthReport? Health { get; init; }

    /// <summary>Gets the time of the observation in the integrated system, if known.</summary>
    public DateTimeOffset? SourceTime { get; init; }

    /// <summary>Gets the connection that reports.</summary>
    public required ConnectionId Connection { get; init; }

    /// <summary>Gets the command this observation answers, if any.</summary>
    public CommandId? CorrelatedCommand { get; init; }
}

/// <summary>The health of a device or server as reported by a connection.</summary>
/// <param name="Connectivity">The connectivity.</param>
/// <param name="Faults">The active faults.</param>
/// <param name="Reason">An optional reason.</param>
public sealed record HealthReport(Connectivity Connectivity, IReadOnlyList<string> Faults, string? Reason);
