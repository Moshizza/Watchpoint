using System.Diagnostics.CodeAnalysis;
using System.Net;
using Watchpoint.Kernel.Ids;
using Watchpoint.Kernel.Results;

namespace Watchpoint.Identity.Contracts;

/// <summary>Sign-in request payload (spec IDN §6.1).</summary>
/// <param name="Login">The user login name.</param>
/// <param name="Password">The plain password.</param>
/// <param name="Client">The client context.</param>
/// <param name="Reason">The reason of the sign-in; required for the break-glass account (spec IDN §11), ignored otherwise.</param>
public sealed record SignInRequest(string Login, string Password, ClientContext Client, string? Reason = null);

/// <summary>Client execution environment and identity context (spec IDN §6.1, §12).</summary>
/// <param name="Kind">Client kind (Desktop, Web, Mobile, Api).</param>
/// <param name="ClientInstanceId">Random identifier generated by the client installation.</param>
/// <param name="WorkstationId">Optional workstation identifier.</param>
/// <param name="RemoteIp">Optional remote IP address.</param>
/// <param name="UserAgent">Optional user-agent string.</param>
/// <param name="AppVersion">Optional application version.</param>
/// <param name="BrowserOrigin">
/// The <c>Origin</c> of a request made by a browser (set by the API from the request headers). A browser can only be the
/// Web client: any other <paramref name="Kind"/> with an origin is refused (spec IDN §12).
/// </param>
/// <param name="WorkstationVerified">
/// Whether the workstation proved its identity with its certificate (mTLS endpoint, spec IDN §12). Only meaningful for
/// <see cref="ClientKind.Desktop"/>; ignored for other kinds.
/// </param>
public sealed record ClientContext(
    ClientKind Kind,
    string ClientInstanceId,
    string? WorkstationId = null,
    IPAddress? RemoteIp = null,
    string? UserAgent = null,
    string? AppVersion = null,
    string? BrowserOrigin = null,
    bool WorkstationVerified = false);

/// <summary>Outcome of a sign-in operation (spec IDN §6.1).</summary>
public abstract record SignInOutcome
{
    /// <summary>Successfully authenticated and issued tokens.</summary>
    /// <param name="Tokens">The token pair and session id.</param>
    /// <param name="User">The signed-in user.</param>
    [SuppressMessage("Naming", "CA1720:Identifier contains type name", Justification = "Name fixed by spec IDN §6.1.")]
    public sealed record Signed(TokenPair Tokens, User User) : SignInOutcome;

    /// <summary>MFA verification is required before token issuance.</summary>
    /// <param name="MfaToken">Short-lived MFA token.</param>
    /// <param name="Methods">Available MFA verification methods.</param>
    public sealed record MfaRequired(string MfaToken, IReadOnlyList<string> Methods) : SignInOutcome;

    /// <summary>Password change is required before access is granted.</summary>
    /// <param name="ChangeToken">Short-lived password change token.</param>
    public sealed record PasswordChangeRequired(string ChangeToken) : SignInOutcome;

    /// <summary>
    /// MFA is required for the user but no method is enrolled: the client must enrol TOTP with the token before anything
    /// else (spec IDN §10). The token allows nothing but <see cref="IAuthenticationService.BeginMfaEnrolmentAsync"/> and
    /// <see cref="IAuthenticationService.CompleteMfaEnrolmentAsync"/>.
    /// </summary>
    /// <param name="EnrolmentToken">Short-lived enrolment token (10 min, single use).</param>
    public sealed record MfaEnrolmentRequired(string EnrolmentToken) : SignInOutcome;
}

/// <summary>The second factor presented after a password sign-in returned <see cref="SignInOutcome.MfaRequired"/> (spec IDN §10).</summary>
/// <param name="MfaToken">The token of the pending sign-in.</param>
/// <param name="Method">The method.</param>
/// <param name="Client">The client context; must be the client that started the sign-in.</param>
/// <param name="Code">The TOTP or recovery code (methods <see cref="MfaMethod.Totp"/> and <see cref="MfaMethod.Recovery"/>).</param>
/// <param name="Assertion">The WebAuthn assertion response as JSON (method <see cref="MfaMethod.WebAuthn"/>).</param>
public sealed record MfaVerification(string MfaToken, MfaMethod Method, ClientContext Client, string? Code = null, string? Assertion = null);

/// <summary>Multi-factor methods (spec IDN §10).</summary>
public enum MfaMethod
{
    /// <summary>Time-based one-time password (RFC 6238).</summary>
    Totp,

    /// <summary>WebAuthn / passkey assertion.</summary>
    WebAuthn,

    /// <summary>Single-use recovery code.</summary>
    Recovery,
}

/// <summary>Re-authentication for a critical command (spec IDN §10): exactly one factor must be given.</summary>
/// <param name="Password">The password of the user.</param>
/// <param name="Totp">A TOTP code.</param>
/// <param name="Assertion">A WebAuthn assertion response as JSON (from <see cref="IAuthenticationService.BeginStepUpWebAuthnAsync"/>).</param>
public sealed record StepUpRequest(string? Password = null, string? Totp = null, string? Assertion = null);

/// <summary>A step-up proof bound to a session (spec IDN §10).</summary>
/// <param name="StepUpToken">The proof to pass with the command.</param>
/// <param name="ExpiresAt">When it expires (5 min after issue).</param>
public sealed record StepUpProof(string StepUpToken, DateTimeOffset ExpiresAt);

/// <summary>Result of a completed MFA enrolment during sign-in: the session tokens and the recovery codes shown once.</summary>
/// <param name="Tokens">The tokens.</param>
/// <param name="RecoveryCodes">The recovery codes (never shown again).</param>
public sealed record MfaEnrolmentCompleted(TokenPair Tokens, RecoveryCodes RecoveryCodes);

/// <summary>Access and refresh token pair issued upon authentication (spec IDN §6.1).</summary>
/// <param name="AccessToken">Encoded JWT access token.</param>
/// <param name="AccessExpiresAt">Expiration instant of the access token.</param>
/// <param name="RefreshToken">Random refresh token (given to the client).</param>
/// <param name="RefreshExpiresAt">Expiration instant of the refresh token.</param>
/// <param name="Session">The session identifier.</param>
public sealed record TokenPair(
    string AccessToken,
    DateTimeOffset AccessExpiresAt,
    string RefreshToken,
    DateTimeOffset RefreshExpiresAt,
    SessionId Session);

/// <summary>Authentication service providing local sign-in, token refresh, and sign-out (spec IDN §6.1).</summary>
public interface IAuthenticationService
{
    /// <summary>Performs local username and password authentication.</summary>
    /// <param name="request">Sign-in request details.</param>
    /// <param name="ct">Cancellation token.</param>
    /// <returns>Sign-in outcome.</returns>
    Task<Result<SignInOutcome>> SignInLocalAsync(SignInRequest request, CancellationToken ct);

    /// <summary>Refreshes an access token using a valid refresh token.</summary>
    /// <param name="refreshToken">The plain refresh token.</param>
    /// <param name="client">The client context.</param>
    /// <param name="ct">Cancellation token.</param>
    /// <returns>A new token pair.</returns>
    Task<Result<TokenPair>> RefreshAsync(string refreshToken, ClientContext client, CancellationToken ct);

    /// <summary>Signs out and revokes a session.</summary>
    /// <param name="session">The session identifier.</param>
    /// <param name="ct">Cancellation token.</param>
    /// <returns>Success or error.</returns>
    Task<Result> SignOutAsync(SessionId session, CancellationToken ct);

    /// <summary>
    /// Completes a sign-in that returned <see cref="SignInOutcome.MfaRequired"/> (spec IDN §10). A wrong factor counts as a
    /// sign-in failure for the lockout; the fifth one invalidates the token. The token is single use and bound to the client.
    /// </summary>
    /// <param name="verification">The factor.</param>
    /// <param name="ct">Cancellation token.</param>
    /// <returns>The tokens, <c>identity.signin.mfa_invalid</c> (no detail), or a status/admission error.</returns>
    Task<Result<TokenPair>> VerifyMfaAsync(MfaVerification verification, CancellationToken ct);

    /// <summary>Starts a WebAuthn assertion for a pending sign-in: the options to pass to the authenticator (single use, 5 min).</summary>
    /// <param name="mfaToken">The token of the pending sign-in.</param>
    /// <param name="client">The client context; must be the client that started the sign-in.</param>
    /// <param name="ct">Cancellation token.</param>
    /// <returns>The ceremony, or <c>identity.signin.mfa_invalid</c>.</returns>
    Task<Result<WebAuthnCeremony>> BeginMfaWebAuthnAsync(string mfaToken, ClientContext client, CancellationToken ct);

    /// <summary>Starts the TOTP enrolment of a sign-in that returned <see cref="SignInOutcome.MfaEnrolmentRequired"/>.</summary>
    /// <param name="enrolmentToken">The enrolment token.</param>
    /// <param name="client">The client context; must be the client that started the sign-in.</param>
    /// <param name="ct">Cancellation token.</param>
    /// <returns>The enrolment (secret and URI), or <c>identity.token.invalid</c>.</returns>
    Task<Result<TotpEnrolment>> BeginMfaEnrolmentAsync(string enrolmentToken, ClientContext client, CancellationToken ct);

    /// <summary>
    /// Confirms the TOTP enrolment with a code and completes the sign-in (status and admission checks run again). The
    /// token is consumed by a successful confirmation only; a wrong code counts as a sign-in failure.
    /// </summary>
    /// <param name="enrolmentToken">The enrolment token.</param>
    /// <param name="code">The TOTP code.</param>
    /// <param name="client">The client context.</param>
    /// <param name="ct">Cancellation token.</param>
    /// <returns>The tokens and the recovery codes, or an error.</returns>
    Task<Result<MfaEnrolmentCompleted>> CompleteMfaEnrolmentAsync(string enrolmentToken, string code, ClientContext client, CancellationToken ct);

    /// <summary>
    /// Re-authenticates the user of a session for a critical command (spec IDN §10) with one factor and returns a proof
    /// valid 5 minutes, bound to the session. A wrong password counts for the lockout.
    /// </summary>
    /// <param name="session">The session the command comes from.</param>
    /// <param name="request">The factor.</param>
    /// <param name="ct">Cancellation token.</param>
    /// <returns>The proof, or <c>identity.stepup.invalid</c>.</returns>
    Task<Result<StepUpProof>> StepUpAsync(SessionId session, StepUpRequest request, CancellationToken ct);

    /// <summary>Starts a WebAuthn assertion for a step-up of the session (single use, 5 min).</summary>
    /// <param name="session">The session.</param>
    /// <param name="ct">Cancellation token.</param>
    /// <returns>The ceremony, or <c>identity.stepup.invalid</c>.</returns>
    Task<Result<WebAuthnCeremony>> BeginStepUpWebAuthnAsync(SessionId session, CancellationToken ct);

    /// <summary>Checks a step-up proof passed with a command: it must belong to <paramref name="session"/>, be unexpired and the session not revoked.</summary>
    /// <param name="stepUpToken">The proof.</param>
    /// <param name="session">The session of the command.</param>
    /// <returns>Success, or <c>identity.stepup.required</c>.</returns>
    Result ValidateStepUp(string stepUpToken, SessionId session);

    /// <summary>
    /// Completes the password change required flow using a changeToken. The sign-in then continues at step 8: the outcome
    /// is <see cref="SignInOutcome.Signed"/>, or <see cref="SignInOutcome.MfaRequired"/> / <see cref="SignInOutcome.MfaEnrolmentRequired"/>
    /// when the user owes a second factor.
    /// </summary>
    /// <param name="changeToken">The change token issued during sign-in.</param>
    /// <param name="newPassword">The new password.</param>
    /// <param name="ct">Cancellation token.</param>
    /// <returns>The outcome, or error.</returns>
    Task<Result<SignInOutcome>> CompletePasswordChangeAsync(string changeToken, string newPassword, CancellationToken ct);
}
